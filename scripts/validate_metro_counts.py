"""Compare exported C113–C119 is_metro labels with #35's real districts (#37).

Run after generating the map: python scripts/validate_metro_counts.py
Writes a CSV and Markdown report under docs/. A failed Congress exits nonzero;
individual state misses remain in the report even when the Congress passes.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONGRESSES = range(113, 120)


def exported_counts(path: Path, congress: int) -> dict[str, tuple[int, int]]:
    """Count actual default-tier labels, rejecting missing or malformed exports."""
    counts: dict[str, tuple[int, int]] = {}
    seen = set()
    for feature in json.loads(path.read_text(encoding="utf-8"))["features"]:
        p = feature["properties"]
        fips = str(p["state_fips"]).zfill(2)
        key = (fips, p["cd_index"])
        if key in seen or p["congress_number"] != congress or type(p.get("is_metro")) is not bool:
            raise ValueError(f"C{congress}: duplicate district, wrong Congress, or invalid is_metro: {key}")
        seen.add(key)
        seats, metro = counts.get(fips, (0, 0))
        counts[fips] = seats + 1, metro + int(p["is_metro"])
    return counts


def compare(benchmark: list[dict], cds_dir: Path) -> list[dict]:
    keys = [(int(r["congress"]), r["state_fips"]) for r in benchmark]
    if len(keys) != len(set(keys)) or set(c for c, _ in keys) != set(CONGRESSES):
        raise ValueError("Benchmark must contain unique state/Congress rows for C113–C119")
    rows = []
    state_sets = []
    for congress in CONGRESSES:
        expected = [r for r in benchmark if int(r["congress"]) == congress]
        states = {r["state_fips"] for r in expected}
        state_sets.append(states)
        if len(states) != 50 or sum(int(r["seats"]) for r in expected) != 435:
            raise ValueError(f"C{congress}: benchmark must cover 50 states and 435 seats")
        actual = exported_counts(cds_dir / f"{congress}.geojson", congress)
        if set(actual) != states:
            raise ValueError(f"C{congress}: exported states do not match benchmark")
        for r in sorted(expected, key=lambda r: r["state_fips"]):
            seats, ours = actual[r["state_fips"]]
            if seats != int(r["seats"]) or ours != int(r["model_metro_seats"]):
                raise ValueError(f"C{congress} {r['state']}: seat count or model snapshot differs; rebuild/check inputs")
            real = int(r["real_metro"])
            if not 0 <= real <= seats:
                raise ValueError(f"C{congress} {r['state']}: invalid real metro count")
            rows.append(dict(congress=congress, state_fips=r["state_fips"], state=r["state"],
                             our_metro_seats=ours, real_metro_seats=real, difference=ours-real,
                             within_one=abs(ours-real) <= 1,
                             real_density250_seats=int(r["real_metro_d250"]),
                             nc_c117_proxy=int(r["nc_c117_proxy"])))
    if any(states != state_sets[0] for states in state_sets):
        raise ValueError("Benchmark state sets differ across Congresses")
    return rows


def summary(rows: list[dict]) -> list[tuple[int, int, int, bool]]:
    result = []
    for c in CONGRESSES:
        group = [r for r in rows if r["congress"] == c]
        passed = sum(r["within_one"] for r in group)
        result.append((c, passed, len(group), passed * 10 >= len(group) * 9))
    return result


# Misses investigated and accepted without changing the comparison (#42).
DOCUMENTED_EXCEPTIONS = {(c, "TX") for c in range(113, 118)}


def within_label(r: dict) -> str:
    if r["within_one"]:
        return "yes"
    return "**NO** (documented)" if (r["congress"], r["state"]) in DOCUMENTED_EXCEPTIONS else "**NO**"


def markdown(rows: list[dict]) -> str:
    lines = ["# Metro seat validation, C113–C119 (#37)", "",
             "Generated by `python scripts/validate_metro_counts.py` from the actual default-tier",
             "`is_metro` labels in `data_processed/polyhex_cds_by_congress/` and the checked-in",
             "`data_raw/congressional_districts/real_metro_counts_c113_c119.csv` benchmark.", "",
             "Difference = our labels − real districts. Pass requires |difference| ≤ 1 for",
             "at least 90% (45/50) of states **in each Congress**; zero-metro states are included.", "",
             "## Result", "", "| Congress | States within ±1 | Share | Result | Density ≥250 share |",
             "|---|---:|---:|---|---:|"]
    for c, passed, total, ok in summary(rows):
        density = sum(abs(r["our_metro_seats"]-r["real_density250_seats"]) <= 1
                      for r in rows if r["congress"] == c)
        lines.append(f"| C{c} | {passed}/{total} | {passed/total:.0%} | {'PASS' if ok else 'FAIL'} | {density/total:.0%} |")
    lines += ["", "## Interpretation and diagnoses", "",
              "The benchmark uses #35's chosen ≥50% population-in-qualifying-UA rule,",
              "rather than a land-area/density cutoff. See [calibration](research_real_district_metro.md).",
              "It shares the model's qualifying metros and UA inputs: this checks seat rounding",
              "and district allocation, not the independent validity of the top-25 cutoff.", "",
              "The independent density ≥250 people/km² comparison is shown separately above;",
              "it fails the 90% criterion because dense smaller metros qualify while sparse",
              "big-metro exurbs do not. It is not substituted for the chosen benchmark.", "",
              "North Carolina C117 uses the flagged C116 boundary proxy; NC has no qualifying",
              "metro in 2010, so the proxy does not change its chosen-rule count.", "",
              "### Texas C113–C117: threshold / district allocation", "",
              "Each of these five state/Congress failures is 17 model seats versus 15 real (+2).",
              "The 2011 district plan splits metro populations across rural-reaching districts:",
              "TX-05/26 (Dallas), TX-36/10 (Houston), and TX-21 (San Antonio) fall below 50%.",
              "The benchmark's 40% sensitivity count is 17 in all five Congresses. This supports",
              "threshold sensitivity to district drawing, rather than evidence of a population",
              "undercount or linkage error. The C118–C119 plan agrees at 19 seats.", "",
              "Treatment ([#42](https://github.com/grumm1728/historicalHexCDs/issues/42)): keep the",
              "majority rule and this comparison unchanged; Texas C113–C117 is a **documented",
              "exception**. Tract assignment and coverage are clean, no near-threshold district",
              "crosses 50% under a 1 km urbanized-area edge perturbation, and Texas has 16.5",
              "population-equivalent metro seats under the 2011 plan (model: 17). See the",
              "[Texas investigation](texas_metro_threshold_c113_c117.md).", "",
              "## Every state and Congress", "",
              "| Congress | State | Our metro seats | Real metro seats | Difference | Within ±1 |",
              "|---|---|---:|---:|---:|---|"]
    for r in rows:
        lines.append(f"| C{r['congress']} | {r['state']} | {r['our_metro_seats']} | {r['real_metro_seats']} | {r['difference']:+d} | {within_label(r)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cds-dir", type=Path, default=ROOT / "data_processed/polyhex_cds_by_congress")
    args = parser.parse_args()
    with (ROOT / "data_raw/congressional_districts/real_metro_counts_c113_c119.csv").open(newline="", encoding="utf-8") as f:
        rows = compare(list(csv.DictReader(f)), args.cds_dir)
    with (ROOT / "docs/metro_validation_c113_c119.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (ROOT / "docs/metro_validation_c113_c119.md").write_text(markdown(rows), encoding="utf-8")
    for c, passed, total, ok in summary(rows):
        print(f"C{c}: {passed}/{total} states within ±1 — {'PASS' if ok else 'FAIL'}")
    raise SystemExit(0 if all(ok for _, _, _, ok in summary(rows)) else 1)


if __name__ == "__main__":
    main()
