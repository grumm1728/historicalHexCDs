"""Texas C113-C117: why the real-district majority rule counts 15 metro seats, not 17 (#42).

Reports, for each 2011-plan Congress, the Texas districts near the >=50% qualifying-metro
population threshold, the count at each cutoff, the plan-independent population-equivalent
metro seats, and a tract assignment/coverage check (tracts outside every district, and
how far tracts near an urbanized-area edge could move each near-threshold district).

Reads the same inputs as scripts/build_real_district_metro.py (needs geopandas) and
writes docs/texas_metro_threshold_c113_c117.md. Run:
    python scripts/diag_texas_metro_threshold.py
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import geopandas as gpd
import pandas as pd
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import build_real_district_metro as b  # noqa: E402
import urban_seats as us  # noqa: E402

TX = "48"
CONGRESSES = range(113, 118)
CUTOFFS = (0.30, 0.35, 0.40, 0.45, 0.50)
NEAR = (0.25, 0.70)       # districts listed in the share table
EDGE_M = 1000             # tracts this close to a qualifying UA edge may be mis-assigned
OUT = ROOT / "docs" / "texas_metro_threshold_c113_c117.md"


def district_table() -> dict[int, list[dict]]:
    with (b.CD_DIR / "real_districts_c113_c119.csv").open(newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["state_fips"] == TX]
    return {c: [r for r in rows if int(r["congress"]) == c] for c in CONGRESSES}


def model_seats() -> dict[int, int]:
    with (b.CD_DIR / "real_metro_counts_c113_c119.csv").open(newline="", encoding="utf-8") as f:
        return {int(r["congress"]): int(r["model_metro_seats"])
                for r in csv.DictReader(f) if r["state_fips"] == TX}


def coverage(near_cds: set[str]) -> dict[int, dict]:
    """Tracts outside every TX district, and the UA-edge bound on each near district."""
    metros = b.metro_geometries(2010)
    raw = pd.read_csv(b.CD_DIR / b.TRACT_FILES[2010], dtype={"STATEFP": str}, encoding="utf-8-sig")
    tracts = b.tract_points(2010, metros).assign(STATEFP=raw.STATEFP.values)
    tracts = tracts[tracts.STATEFP == TX]
    ua_edge = unary_union(list(metros.values())).boundary
    tracts = tracts.assign(d_edge=tracts.geometry.distance(ua_edge))
    out = {}
    for c in CONGRESSES:
        cds = gpd.read_file(b.CD_DIR / b.CD_FILES[c])
        col = next(x for x in cds.columns if x.startswith("CD") and x.endswith("FP"))
        cds = cds[cds.STATEFP == TX].to_crs(b.EQUAL_AREA)[[col, "geometry"]]
        j = gpd.sjoin(tracts, cds, how="left", predicate="within")
        if j.index.duplicated().any():
            raise RuntimeError(f"C{c}: a tract center falls in two districts")
        outside = j[j[col].isna()]
        bounds = {}
        for cd in near_cds:
            g = j[j[col] == cd]
            tot, met = g.POPULATION.sum(), g[g.metro.notna()].POPULATION.sum()
            edge = g[g.d_edge < EDGE_M]
            lo = met - edge[edge.metro.notna()].POPULATION.sum()
            hi = met + edge[edge.metro.isna()].POPULATION.sum()
            bounds[cd] = (lo / tot, hi / tot)
        out[c] = dict(state_pop=int(tracts.POPULATION.sum()),
                      census_pop=us._state_counts(TX, c)[0],
                      outside_n=len(outside), outside_pop=int(outside.POPULATION.sum()),
                      outside_metro_pop=int(outside[outside.metro.notna()].POPULATION.sum()),
                      bounds=bounds)
    return out


def markdown(tables: dict[int, list[dict]], model: dict[int, int], cov: dict[int, dict]) -> str:
    near = {c: sorted((r for r in rows if NEAR[0] <= float(r["metro_pop_frac"]) < NEAR[1]),
                      key=lambda r: -float(r["metro_pop_frac"])) for c, rows in tables.items()}
    cds = sorted({r["cd"] for rows in near.values() for r in rows},
                 key=lambda cd: -float(next(r for r in near[113] + near[117] if r["cd"] == cd)["metro_pop_frac"]))
    lines = ["# Texas C113–C117 metro threshold investigation (#42)", "",
             "Generated by `python scripts/diag_texas_metro_threshold.py`. Follow-up to the",
             "[#37 validation](metro_validation_c113_c119.md): under the real-district ≥50% rule,",
             "Texas has 15 metro seats in C113–C117, but our model has 17.", "",
             "## Near-threshold districts", "",
             "Share of each district's tract population inside a qualifying (top-25) metro's",
             f"urbanized areas, for districts between {NEAR[0]:.0%} and {NEAR[1]:.0%}.",
             f"Bound = the share's range if every tract within {EDGE_M} m of a qualifying UA edge",
             "were assigned to the other side.", "",
             "| District | Metro | " + " | ".join(f"C{c}" for c in CONGRESSES) + " | Edge bound (C113) |",
             "|---|---|" + "---:|" * len(CONGRESSES) + "---|"]
    for cd in cds:
        name = next(r["metro_name"] for c in CONGRESSES for r in tables[c] if r["cd"] == cd)
        shares = []
        for c in CONGRESSES:
            r = next(r for r in tables[c] if r["cd"] == cd)
            s = float(r["metro_pop_frac"])
            shares.append(f"**{s:.1%}**" if s >= 0.5 else f"{s:.1%}")
        lo, hi = cov[113]["bounds"][cd]
        lines.append(f"| TX-{cd} | {name.split('--')[0]} | " + " | ".join(shares) + f" | {lo:.1%}–{hi:.1%} |")
    lines += ["", "## Count by cutoff", "",
              "| Congress | Model | " + " | ".join(f"≥{t:.0%}" for t in CUTOFFS)
              + " | Population-equivalent seats |",
              "|---|---:|" + "---:|" * len(CUTOFFS) + "---:|"]
    for c in CONGRESSES:
        rows = tables[c]
        counts = [sum(float(r["metro_pop_frac"]) >= t for r in rows) for t in CUTOFFS]
        equiv = sum(float(r["metro_pop_frac"]) * int(r["tract_pop"]) / int(r["ideal_pop"]) for r in rows)
        lines.append(f"| C{c} | {model[c]} | " + " | ".join(map(str, counts)) + f" | {equiv:.2f} |")
    lines += ["", "Population-equivalent seats = Σ (district metro population ÷ ideal district",
              "population): the metro seats a plan-independent, population-proportional count gives.",
              "", "## Tract assignment and coverage", "",
              "| Congress | Tract pop. | Census pop. | Tracts outside every district | Their pop. | In a metro |",
              "|---|---:|---:|---:|---:|---:|"]
    for c in CONGRESSES:
        v = cov[c]
        lines.append(f"| C{c} | {v['state_pop']:,} | {v['census_pop']:,} | {v['outside_n']} | "
                     f"{v['outside_pop']:,} | {v['outside_metro_pop']:,} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    tables = district_table()
    near_cds = {r["cd"] for rows in tables.values() for r in rows
                if NEAR[0] <= float(r["metro_pop_frac"]) < NEAR[1]}
    cov = coverage(near_cds)
    text = markdown(tables, model_seats(), cov)
    OUT.write_text(text + FINDINGS, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


FINDINGS = """
## Findings

- **Not a data error.** Every 2010 Texas tract is counted (tract total = census total).
  The few tracts whose center of population falls outside every 1:500k district polygon
  (coastal generalization) hold 0.03% of the population and none is in a qualifying metro,
  so assigning them to the nearest district changes no metro share. No tract falls in two
  districts. Moving every tract within 1 km of a qualifying UA edge to the other side
  still leaves every near-threshold district on the same side of 50% (TX-36 reaches at
  most 49.6%; TX-35 stays at 54% or more).
- **Threshold sensitivity to the 2011 plan.** Five districts (TX-36/10 Houston, TX-05/26
  Dallas, TX-21 San Antonio) combine a metro core with rural or exurban territory and sit
  between 31% and 47%. At ≥40% the count is 17, which equals the model.
- **The model is population-proportional, as designed.** Texas has 16.5
  population-equivalent metro seats under the 2011 plan, and the model's 17 is within 1 of
  that. The 2021 plan (C118–C119) draws metro districts more compactly, and the majority
  rule then agrees with the model at 19.

## Chosen treatment

Keep the ≥50% majority rule, the benchmark CSV, the model, and the original pass/fail
comparison unchanged. Record Texas C113–C117 as a **documented exception**: the 2011
plan's metro-plus-rural districts make the majority count fall 2 below the population
share, not the model or its inputs. Do not tune UA linkage, populations, rounding, or the
threshold to fit these counts.

Effect on all-state validation: none. C113–C117 still pass at 49/50 states within ±1;
Texas remains the single listed miss in the [validation report](metro_validation_c113_c119.md)
and is marked there as a documented exception.
"""


if __name__ == "__main__":
    main()
